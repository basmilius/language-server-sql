//! Every token and node kind of the syntax tree, in one enum so rowan can store it as a `u16`. The
//! keywords are the words the grammar looks for, in one sorted table the lexer searches.

macro_rules! syntax_kinds {
    ($($name:ident),* $(,)?) => {
        /// The kind of a token or a node.
        #[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
        #[repr(u16)]
        #[allow(non_camel_case_types, clippy::upper_case_acronyms)]
        pub enum SyntaxKind {
            $($name),*
        }

        impl SyntaxKind {
            /// Every kind in declaration order; the index is the raw value.
            pub const ALL: &'static [SyntaxKind] = &[$(SyntaxKind::$name),*];

            /// The name of the variant, as the tree dump prints it.
            pub fn name(self) -> &'static str {
                match self {
                    $(SyntaxKind::$name => stringify!($name)),*
                }
            }
        }
    };
}

