/// The length of the longest keyword, past which a word is never one.
pub(crate) const LONGEST_KEYWORD: usize = 19;

impl SyntaxKind {
    /// Whitespace and comments, which the parser keeps in the tree but never looks at.
    pub fn is_trivia(self) -> bool {
        matches!(
            self,
            SyntaxKind::WHITESPACE | SyntaxKind::LINE_COMMENT | SyntaxKind::BLOCK_COMMENT
        )
    }

    /// A word the grammar looks for. A keyword that names something, as `date` in `SELECT date FROM
    /// t`, keeps its kind and stands in a `NAME` node.
    pub fn is_keyword(self) -> bool {
        self >= SyntaxKind::ABORT_KW && self <= SyntaxKind::ZONE_KW
    }

    /// A token as opposed to a node.
    pub fn is_token(self) -> bool {
        self < SyntaxKind::SOURCE_FILE
    }

    /// A quoted or unquoted identifier.
    pub fn is_identifier(self) -> bool {
        matches!(
            self,
            SyntaxKind::IDENT | SyntaxKind::QUOTED_IDENT | SyntaxKind::BACKTICK_IDENT | SyntaxKind::BRACKET_IDENT
        )
    }

    /// A string literal of any form.
    pub fn is_string(self) -> bool {
        matches!(
            self,
            SyntaxKind::STRING
                | SyntaxKind::ESCAPE_STRING
                | SyntaxKind::NATIONAL_STRING
                | SyntaxKind::UNICODE_STRING
                | SyntaxKind::BIT_STRING
                | SyntaxKind::HEX_STRING
                | SyntaxKind::DOLLAR_STRING
        )
    }

    /// The keyword spelled `word`, in any case.
    pub fn from_keyword(word: &str) -> Option<SyntaxKind> {
        if word.len() > LONGEST_KEYWORD || !word.is_ascii() {
            return None;
        }
        let mut buffer = [0u8; LONGEST_KEYWORD];
        let upper = &mut buffer[..word.len()];
        upper.copy_from_slice(word.as_bytes());
        upper.make_ascii_uppercase();
        KEYWORDS
            .binary_search_by(|(spelling, _)| spelling.as_bytes().cmp(upper))
            .ok()
            .map(|index| KEYWORDS[index].1)
    }
}

impl lsc_syntax::TokenKind for SyntaxKind {
    const EOF: SyntaxKind = SyntaxKind::EOF;
    const ERROR: SyntaxKind = SyntaxKind::ERROR;

    fn is_trivia(self) -> bool {
        SyntaxKind::is_trivia(self)
    }

    fn is_whitespace(self) -> bool {
        self == SyntaxKind::WHITESPACE
    }
}

/// The rowan language marker for SQL.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum SqlLanguage {}

impl rowan::Language for SqlLanguage {
    type Kind = SyntaxKind;

    fn kind_from_raw(raw: rowan::SyntaxKind) -> SyntaxKind {
        SyntaxKind::ALL[raw.0 as usize]
    }

    fn kind_to_raw(kind: SyntaxKind) -> rowan::SyntaxKind {
        rowan::SyntaxKind(kind as u16)
    }
}

pub type SyntaxNode = rowan::SyntaxNode<SqlLanguage>;
pub type SyntaxToken = rowan::SyntaxToken<SqlLanguage>;
pub type SyntaxElement = rowan::SyntaxElement<SqlLanguage>;
